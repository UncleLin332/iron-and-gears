import random
import time

class Card:
    def __init__(self, name, cost, atk, hp, text=""):
        self.name = name
        self.cost = cost
        self.atk = atk
        self.max_hp = hp
        self.hp = hp
        self.text = text
        self.has_attacked = False # 新增屬性：本回合是否已攻擊過

    def __str__(self):
        effect = f" | 效果: {self.text}" if self.text else ""
        return f"【{self.name}】({self.cost}費) {self.atk}/{self.hp}{effect}"

class Player:
    def __init__(self, name):
        self.name = name
        self.hp = 30
        self.max_fuel = 0
        self.fuel = 0
        self.deck = []
        self.hand = []
        self.board = []

    def init_deck(self):
        # 放入我們設計的經典龐克卡牌的模板
        cards_pool_templates = [
            Card("原型蒸汽壓路機", 4, 4, 5),
            Card("熱心的工坊學徒", 2, 2, 2, "報廢:隨機部署陷阱"),
            Card("報廢蒸氣巨獸", 5, 3, 5, "攔截(嘲諷)"),
            Card("王牌拆解手", 5, 4, 2, "部署:摧毀大於7攻的機械"),
            Card("巨型時鐘巨靈", 10, 8, 8, "回合結束未用燃料可減費"),
            Card("普通的自走齒輪", 1, 1, 1),
            # New card goes here
            # Card("新卡名稱", 費用, 攻擊, 生命, "效果文字")
            Card("龐可汽車", 1, 1, 1),
        ]
        # 隨機選擇模板並創建新的卡牌實例來填充牌組
        self.deck = []
        for _ in range(30):
            template_card = random.choice(cards_pool_templates)
            # Create a *new* instance for each card in the deck
            new_card = Card(template_card.name, template_card.cost, template_card.atk, template_card.hp, template_card.text)
            self.deck.append(new_card)
        random.shuffle(self.deck)

    def draw_card(self):
        if self.deck:
            card = self.deck.pop(0)
            if len(self.hand) < 10:
                self.hand.append(card)
                print(f"[{self.name}] 抽到了 {card.name}")
            else:
                print(f"[{self.name}] 手牌滿了！{card.name} 被燒毀了！")
        else:
            print(f"[{self.name}] 沒有牌可以抽了！受到疲勞傷害！")
            self.hp -= 1

    def start_turn(self, turn_num):
        self.max_fuel = min(turn_num, 10)
        self.fuel = self.max_fuel
        self.draw_card()
        # 重置所有場上生物的攻擊狀態
        for card in self.board:
            card.has_attacked = False

def show_game_state(p1, p2):
    print("\n" + "="*50)
    print(f"對手 [{p2.name}] 血量: {p2.hp} | 燃料: {p2.fuel}/{p2.max_fuel} | 手牌數: {len(p2.hand)}")
    print(f"對手戰場: " + " ｜ ".join([f"{c.name}({c.atk}/{c.hp})" for c in p2.board]) if p2.board else "[空]")
    print("-"*50)
    print(f"玩家戰場: " + " ｜ ".join([f"{c.name}({c.atk}/{c.hp})" + (" (已攻擊)" if c.has_attacked else "") for c in p1.board]) if p1.board else "[空]")
    print(f"玩家 [{p1.name}] 血量: {p1.hp} | 燃料: {p1.fuel}/{p1.max_fuel}")
    print("玩家手牌:")
    for i, card in enumerate(p1.hand):
        print(f"  [{i}] {card}")
    print("="*50)

def game_loop():
    print("⚙️  歡迎來到《鐵律與齒輪》(Iron & Gears) 原型測試版 ⚙️\n")
    player = Player("林工程師")
    ai = Player("自動化AI")

    player.init_deck()
    ai.init_deck()

    # 起始抽牌
    for _ in range(3): player.draw_card()
    for _ in range(3): ai.draw_card()

    turn = 1
    while player.hp > 0 and ai.hp > 0:
        # ---- 玩家回合 ----
        player.start_turn(turn)

        # 簡單模擬：AI 每回合會隨機下一張牌到場上，方便玩家測試戰場交換
        if ai.hand:
            playable = [c for c in ai.hand if c.cost <= ai.fuel]
            if playable:
                c = random.choice(playable)
                ai.hand.remove(c)
                ai.board.append(c)

        while True:
            show_game_state(player, ai)
            print("請選擇行動: [1] 部署手牌 [2] 攻擊 [3] 結束回合 [4] 投降")
            choice = input("請輸入數字: ")

            if choice == "1":
                if not player.hand:
                    print("❌ 手中沒有卡牌！")
                    continue
                idx = input("請輸入想部署的手牌編號 (0, 1, 2...): ")
                try:
                    idx = int(idx)
                    card = player.hand[idx]
                    if player.fuel >= card.cost:
                        player.fuel -= card.cost
                        player.hand.pop(idx)
                        player.board.append(card)
                        print(f"⚙️ 成功部署 {card.name}！")
                    else:
                        print("❌ 燃料不足！")
                except (ValueError, IndexError):
                    print("❌ 輸入錯誤！請輸入有效數字或編號。")

            elif choice == "2": # 攻擊
                if not player.board:
                    print("❌ 你沒有手下可以發動攻擊！")
                    continue

                print("\n你的戰場:")
                for i, c in enumerate(player.board): print(f"  [{i}] {c.name}({c.atk}/{c.hp})" + (" (已攻擊)" if c.has_attacked else ""))

                try:
                    my_idx = int(input("選擇你的手下編號: "))
                    my_m = player.board[my_idx]

                    if my_m.has_attacked:
                        print(f"❌ 你的 {my_m.name} 本回合已經攻擊過了！")
                        continue

                    if not ai.board: # 對手場上沒有手下，可以選擇攻擊玩家
                        print("對手戰場上沒有手下，你的手下可以直接攻擊對手英雄。")
                        ai.hp -= my_m.atk
                        print(f"💥 你的 {my_m.name} 對對手英雄造成了 {my_m.atk} 點傷害！")
                        my_m.has_attacked = True # 標記為已攻擊
                    else: # 對手場上有手下，必須先處理手下交換
                        print("對手戰場:")
                        for i, c in enumerate(ai.board): print(f"  [{i}] {c.name}({c.atk}/{c.hp})")
                        en_idx = int(input("選擇對手的手下編號: "))

                        en_m = ai.board[en_idx]

                        # 進行經典的卡牌血量交換計算
                        print(f"💥 {my_m.name} 與 {en_m.name} 發生鋼鐵碰撞！")
                        my_m.hp -= en_m.atk
                        en_m.hp -= my_m.atk
                        my_m.has_attacked = True # 標記為已攻擊

                        # 死亡判定
                        if my_m.hp <= 0:
                            print(f"💀 你的 {my_m.name} 報廢了！")
                            player.board.pop(my_idx)
                        if en_m.hp <= 0:
                            print(f"💀 對手的 {en_m.name} 報廢了！")
                            ai.board.pop(en_idx)
                except (ValueError, IndexError):
                    print("❌ 輸入錯誤！請選擇有效的手下編號。")

            elif choice == "3":
                print("結束回合，輪到對手...")
                break
            elif choice == "4":
                player.hp = 0
                break

        # 簡單判定對手打臉
        if ai.board and not player.board:
            for c in ai.board:
                player.hp -= c.atk
                print(f"💢 對手的 {c.name} 直接對你造成了 {c.atk} 點傷害！")

        turn += 1
        time.sleep(1)

    print("\n遊戲結束！")
    if player.hp <= 0:
        print("💀 你的工坊核心過熱爆炸了，輸掉了對戰！")
    else:
        print("🏆 恭喜！你成功的用精湛的鋼鐵擊敗了對手！")

if __name__ == "__main__":
    game_loop()